class Handler(BaseHTTPRequestHandler):
    def do_GET(self):
        try:
            path = urlparse(self.path).path
            if path == "/api/health":
                self.json({"status": "ok"})
            elif path == "/api/nonconformities":
                self.json({"items": list_nonconformities()})
            elif path.startswith("/api/root-cause/"):
                self.json(analyze_root_cause(unquote(path.rsplit("/", 1)[-1])))
            elif path.startswith("/api/traceability/"):
                self.json(trace_lot(unquote(path.rsplit("/", 1)[-1])))
            else:
                self.static(path)
        except ValueError as exc:
            self.json({"error": str(exc)}, HTTPStatus.BAD_REQUEST)
        except KeyError as exc:
            self.json({"error": str(exc).strip("'")}, HTTPStatus.NOT_FOUND)

    def do_POST(self):
        try:
            if urlparse(self.path).path != "/api/nonconformities":
                self.json({"error": "Rota nao encontrada."}, HTTPStatus.NOT_FOUND)
                return
            length = int(self.headers.get("Content-Length", "0"))
            payload = json.loads(self.rfile.read(length).decode("utf-8"))
            self.json(create_nonconformity(payload), HTTPStatus.CREATED)
        except ValueError as exc:
            self.json({"error": str(exc)}, HTTPStatus.BAD_REQUEST)

    def static(self, path):
        target = FRONTEND / ("index.html" if path in ("", "/") else path.lstrip("/"))
        if not target.exists():
            self.json({"error": "Arquivo nao encontrado."}, HTTPStatus.NOT_FOUND)
            return
        content_type = "text/css" if target.suffix == ".css" else "application/javascript" if target.suffix == ".js" else "text/html"
        body = target.read_bytes()
        self.send_response(HTTPStatus.OK)
        self.send_header("Content-Type", content_type)
        self.send_header("Content-Length", str(len(body)))
        self.end_headers()
        self.wfile.write(body)

    def json(self, data, status=HTTPStatus.OK):
        body = json.dumps(data, ensure_ascii=False).encode("utf-8")
        self.send_response(status)
        self.send_header("Content-Type", "application/json; charset=utf-8")
        self.send_header("Content-Length", str(len(body)))
        self.end_headers()
        self.wfile.write(body)


