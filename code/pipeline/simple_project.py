def _load_template_files() -> dict[str, str]:
    template_root = Path(__file__).resolve().parent / "simple_templates"
    if not template_root.exists():
        return FILES
    loaded = dict(FILES)
    for path in template_root.rglob("*"):
        if "__pycache__" in path.parts or path.suffix == ".pyc":
            continue
        if path.is_file():
            loaded[str(path.relative_to(template_root)).replace("\\", "/")] = path.read_text(encoding="utf-8")
    return loaded


FILES = _load_template_files()
